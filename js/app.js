const patternSelector =
    document.getElementById("patternSelector");

const analyzePatternButton =
    document.getElementById("analyzePatternButton");

const patternResult =
    document.getElementById("patternResult");

const patternTitle =
    document.getElementById("patternTitle");

const patternExplanation =
    document.getElementById("patternExplanation");

const patternRecommendation =
    document.getElementById("patternRecommendation");


